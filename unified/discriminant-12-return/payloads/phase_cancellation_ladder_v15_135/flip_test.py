"""
Flip test (sandbox, 2026-10-29): gravity creates the quarter grid; a phase
offset creates EM as a sector of it.

Setup: the quarter checkerboard of ladder_test.py Part 1 -- points (C, X)
with C, X in (1/4)Z and 4C = 4X (mod 2), generated by C = (A+B)/2,
X = (A-B)/2 for A, B in (1/2)Z.

Claim under test: a staggered phase offset -- a second channel translated by
half a period, so its rung amplitudes carry the sign chi = (-1)^(4C) --
interferes as (1 + chi)/2 and leaves exactly the EM sublattice
C, X in (1/2)Z, cancelling every odd-quarter point. The complementary
projector (1 - chi)/2 leaves exactly the odd quarters (gravity-only rungs).
"""
from fractions import Fraction as F

pts = set()
for p in range(-16, 17):
    for q in range(-16, 17):
        A, B = F(p, 2), F(q, 2)
        pts.add(((A + B) / 2, (A - B) / 2))

def chi(C):
    return 1 if (4 * C) % 2 == 0 else -1   # (-1)^(4C): +1 on halves, -1 on odd quarters

surv, killed = [], []
for (C, X) in sorted(pts):
    ((surv if chi(C) == 1 else killed).append((C, X)))

em_ok = all(C.denominator <= 2 and X.denominator <= 2 for (C, X) in surv)
odd_ok = all(C.denominator == 4 and X.denominator == 4 for (C, X) in killed)
print("checkerboard points:", len(pts))
print("phase-offset survivors:", len(surv), " -- all in (1/2)Z x (1/2)Z (EM):", em_ok)
print("cancelled points:     ", len(killed), " -- all odd quarters (gravity-only):", odd_ok)
print("quotient (1/4 Z)/(1/2 Z) has order", 2, "-- Z2: EM is one parity sector of the grid")
print("ladder reading: if U steps one quarter rung, the EM ladder is U^2;")
print("the phase offset is the Z4 -> Z2 grading character of the gravity ladder.")
