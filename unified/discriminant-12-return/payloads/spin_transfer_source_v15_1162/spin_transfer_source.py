#!/usr/bin/env python3
"""
spin_transfer_source.py -- follow-on item (sandbox,
2026-11-18): the gravity-to-spin transfer operator of
v15.1128's [O], completed at the one point the chain
still imported: the Zeeman gradient.

Chain as filed: tidal torque tau = g dQ sin(2th)
(v15.1128 Gate 1030); torsional susceptibility chi_th
(Gate 1031); Zeeman readout with IMPORTED gradient
field B = (G z, 0, B0 + G x), giving dOm(th) =
gamma G d cos(th) and the full transfer dCxy/g
(v15.1131 Gates 1034-1035, Audit R600); two-channel
separation (v15.1132). In v15.1131 the gradient G is
"externally generated by distant coils" -- a prescribed
coefficient. Here it is DERIVED from an explicit
current source, and the exact (nonlinear) transfer is
computed from the same source.

Source: two infinite straight wires parallel to y at
(x, z) = (+a, 0) and (-a, 0), carrying EQUAL currents
+I along +y (Biot-Savart), plus a Helmholtz pair
supplying the uniform B0 (its gradient at center
vanishes by symmetry). The wire pair's field in the
measurement region is the quadrupole gradient field of
v15.1131 with a DERIVED coefficient.

Gates:
W1. The wire-pair field is exactly divergence- and
    curl-free in the source-free region (symbolic).
W2. Its Taylor expansion at the origin is
    B = (G z, 0, G x) + O(3) with G = mu0 I/(pi a^2)
    -- v15.1131's imported G is the leading coefficient
    of an explicit source. (B0 is external, from the
    Helmholtz pair; W4.)
W3. Exact sensor splitting from the source field: at
    r_A = +(d/2)(cos th, sin th, 0), r_B = -r_A,
    dOm_exact(th) = gamma G d cos(th) /
                    (1 - (d cos th/(2a))^2)
    -- v15.1131's gamma G d cos(th) is the leading term;
    the correction factor is exact and computable.
W4. Helmholtz B0: on-axis field of an equal-current
    loop pair is even about the center, so its gradient
    vanishes there identically.
W5. Assembled source-derived transfer: v15.1131's
    dCxy/g with G -> mu0 I/(pi a^2) and the exact
    angular factor from W3's derivative; the transfer
    vanishes identically at I = 0 -- the operator's
    off-switch sits exactly at the (now explicit)
    laboratory input, the coil current.

Scope: the completed operator is a composition of
standard maps (tidal torque -> torsion -> Biot-Savart
Zeeman -> Ramsey). No cone coefficient enters. The
DIRECT gravity-to-spin channel remains absent for
point spins (v15.1128 Gate 1032 stands: Q_spin does
not couple S/T0; gravity reaches the spins only
through their carriers' positions). Still open and
NOT touched here: v15.1132's backaction/noise model
and the K4-vs-Einstein-Maxwell matched comparison.
"""
import sympy as sp

fails = []
def check(name, cond):
    print(("PASS " if cond else "FAIL ") + name)
    if not cond: fails.append(name)

x, z, a, I, mu0 = sp.symbols("x z a I mu0", positive=True)
# wire pair: +I along y at (+a,0) and (-a,0); B of a y-wire
# at (x0,0): (mu0 Iw/2pi) (z, 0, -(x-x0)) / ((x-x0)^2+z^2)
def wire(x0, Iw):
    r2 = (x - x0)**2 + z**2
    return (mu0 * Iw / (2 * sp.pi)) * sp.Matrix([z, 0, -(x - x0)]) / r2
B = wire(a, I) + wire(-a, I)
Bx, Bz = B[0], B[2]

# W1: div and curl (2D reduction, fields y-independent)
divB = sp.simplify(sp.diff(Bx, x) + sp.diff(Bz, z))
curl_y = sp.simplify(sp.diff(Bx, z) - sp.diff(Bz, x))
check("W1 wire-pair field: div B = 0 and curl B = 0 in the source-free region",
      divB == 0 and curl_y == 0)

# W2: Taylor at origin
Bx_s = sp.series(Bx, x, 0, 2).removeO()
Bx_s = sp.series(Bx_s, z, 0, 2).removeO()
Bz_s = sp.series(Bz, x, 0, 2).removeO()
Bz_s = sp.series(Bz_s, z, 0, 2).removeO()
G_derived = mu0 * I / (sp.pi * a**2)
check("W2a Bz linear term = G x with G = mu0 I/(pi a^2) (derived, not imported)",
      sp.simplify(sp.expand(Bz_s).coeff(x, 1) - G_derived) == 0
      and sp.expand(Bz_s).coeff(z, 1) == 0)
check("W2b Bx linear term = G z, and dBx/dz = dBz/dx = G (Maxwell-consistent)",
      sp.simplify(sp.expand(Bx_s).coeff(z, 1) - G_derived) == 0)

# W3: exact splitting at the sensor positions (z = 0 plane)
th, d, gamma = sp.symbols("theta d gamma", real=True)
xA = (d / 2) * sp.cos(th)
Bz_at = lambda xx: sp.simplify(Bz.subs({z: 0, x: xx}))
dOm_exact = sp.simplify(gamma * (Bz_at(xA) - Bz_at(-xA)))
target = gamma * G_derived * d * sp.cos(th) / (1 - (d * sp.cos(th) / (2 * a))**2)
check("W3a exact dOm = gamma G d cos(th)/(1 - (d cos th/(2a))^2) from the source field",
      sp.simplify(dOm_exact - target) == 0)
ratio = dOm_exact / (gamma * G_derived * d * sp.cos(th))
lead = sp.series(ratio, d, 0, 2).removeO()
corr2 = sp.expand(sp.series(ratio, d, 0, 3).removeO()).coeff(d, 2)
print(f"   first correction coefficient (d^2): {corr2}")
check("W3b leading term in d/a is exactly v15.1131's gamma G d cos(th) "
      "(correction starts at (d cos th/(2a))^2)",
      sp.simplify(lead - 1) == 0
      and sp.simplify(corr2 - sp.cos(th)**2 / (4 * a**2)) == 0)

# W4: Helmholtz pair on-axis field is even about center
zz, R, s = sp.symbols("zz R s", real=True)
def loop_field(zv):
    return (R**2) / (R**2 + (zv))**sp.Rational(3, 2)  # up to common factor
Baxis = loop_field((zz - s)**2) + loop_field((zz + s)**2)
check("W4 Helmholtz pair: on-axis B(z) is even in z -> gradient zero at center",
      sp.simplify(Baxis.subs(zz, -zz) - Baxis) == 0)

# W5: assembled transfer null at I = 0 and structure
kappa_, Irot, Gam, om, tau, dQ, phib, WR = sp.symbols(
    "kappa Irot Gamma omega tau DeltaQ phi_bias W_R", real=True)
th0 = sp.symbols("theta0", real=True)
dOm_dth = sp.diff(dOm_exact, th)
transfer = (-2 * sp.sin(phib) * tau * dQ * sp.sin(2 * th0)
            * (dOm_dth.subs(th, th0) / (-gamma * G_derived * d * sp.sin(th0)))
            * gamma * G_derived * d * sp.sin(th0)
            / (kappa_ - Irot * om**2 - sp.I * Gam * om))
check("W5a transfer vanishes identically when the coil current I = 0",
      sp.simplify(transfer.subs(I, 0)) == 0)
check("W5b with the exact angular factor, transfer is finite and proportional "
      "to the derived G at leading order",
      sp.simplify(sp.diff(transfer, I).subs(I, 0)) != 0)

print("FAILURES:", fails if fails else "none")
raise SystemExit(1 if fails else 0)
